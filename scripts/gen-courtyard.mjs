// One-off Muse Image generation of the first screen's home photos, into public/demo/.
// Usage: node scripts/gen-courtyard.mjs             (the three home photos)
//        node scripts/gen-courtyard.mjs courtyard   (only the original fallback)
//        node scripts/gen-courtyard.mjs home-window (any subset, by name)
// Then:  node scripts/demo-variants.mjs              (writes the 390/780 WebP widths)
// To use one as the default photo, change DEFAULT_IMAGE in lib/hero.ts.
// The key comes from META_API_KEY in the environment (or .env.local); it is
// never printed, logged, or written anywhere by this script.
import { mkdirSync, readFileSync, writeFileSync } from "fs";

function loadDotEnvLocal() {
  const env = { ...process.env };
  try {
    for (const line of readFileSync(".env.local", "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)=(.*)$/);
      if (m && !env[m[1]]) env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
    }
  } catch {
    // No .env.local — environment only.
  }
  return env;
}

const MODEL = "muse-image-1.0"; // mirrors PROVIDERS.meta.imageModel in lib/config.ts
const NO_PEOPLE = "No people, no animals, no text, no house numbers, no street signs.";

// name -> output file and prompt. Square 1024. All synthetic; none shows a person.
const JOBS = {
  "home-courtyard": {
    file: "public/demo/home-courtyard.jpg",
    prompt:
      "Photorealistic North-Indian haveli courtyard at morning: a tulsi plant on a raised brick platform in the centre, " +
      "a string cot (charpai) to one side, polished brass pots, warm lime-washed plaster walls, arched doorways, soft golden light. " +
      `${NO_PEOPLE} Cozy, quiet, timeless.`,
  },
  "home-balcony": {
    file: "public/demo/home-balcony.jpg",
    prompt:
      "Photorealistic city apartment balcony in India at golden hour, full of potted plants, a railing and a few chairs, " +
      "warm low sun, a soft view of rooftops beyond. " +
      `${NO_PEOPLE} Peaceful and lived-in.`,
  },
  "home-window": {
    file: "public/demo/home-window.jpg",
    prompt:
      "Photorealistic old wooden window with weathered paint, open shutters, a row of marigolds in pots on the sill, " +
      "soft morning light falling into the room. " +
      `${NO_PEOPLE} Gentle and warm.`,
  },
  // The original fallback photo, kept so it can be regenerated by name.
  courtyard: {
    file: "public/demo/courtyard.jpg",
    prompt:
      "Photorealistic warm sunlit traditional courtyard at morning: an arched wooden doorway, " +
      "weathered plaster walls, potted plants, soft golden light and gentle shadows. " +
      `${NO_PEOPLE} Cozy, quiet, timeless.`,
  },
};

const wanted = process.argv.slice(2);
const names = wanted.length ? wanted : ["home-courtyard", "home-balcony", "home-window"];
for (const n of names) {
  if (!JOBS[n]) {
    console.error(`unknown photo "${n}". Choose from: ${Object.keys(JOBS).join(", ")}`);
    process.exit(2);
  }
}

const key = loadDotEnvLocal().META_API_KEY;
if (!key) {
  console.error("META_API_KEY is missing. Nothing was called.");
  process.exit(2);
}

mkdirSync("public/demo", { recursive: true });
for (const name of names) {
  const job = JOBS[name];
  const startedAt = new Date().toISOString();
  const res = await fetch("https://api.meta.ai/v1/images/generations", {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${key}` },
    body: JSON.stringify({ model: MODEL, prompt: job.prompt, size: "1024x1024", n: 1 }),
  });
  if (!res.ok) {
    console.error(`${name}: image request failed: provider-http-${res.status}`);
    process.exit(1);
  }
  const data = await res.json();
  const first = data?.data?.[0];
  let bytes;
  if (typeof first?.b64_json === "string") {
    bytes = Buffer.from(first.b64_json, "base64");
  } else if (typeof first?.url === "string") {
    const dl = await fetch(first.url);
    if (!dl.ok) {
      console.error(`${name}: image download failed: provider-http-${dl.status}`);
      process.exit(1);
    }
    bytes = Buffer.from(await dl.arrayBuffer());
  } else {
    console.error(`${name}: unexpected image payload keys: ${Object.keys(data).join(",")}`);
    process.exit(1);
  }
  writeFileSync(job.file, bytes);
  // llm_calls record: only metadata + cost/usage as returned by the provider.
  const record = { at: startedAt, model: MODEL, purpose: `home-photo:${name}`, bytes: bytes.length, usage: data.usage ?? null, cost_usd: typeof data.cost_usd === "number" ? data.cost_usd : null };
  console.log(`llm_calls ${JSON.stringify(record)}`);
  console.log(`saved ${job.file} (${bytes.length} bytes)`);
}
console.log("next: node scripts/demo-variants.mjs");
