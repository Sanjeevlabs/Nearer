const wanted = process.argv.slice(2);
const names = wanted.length ? wanted : ["home-courtyard", "home-balcony", "home-window"];
for (const n of names) {
  if (!JOBS[n]) {
    console.error(`unknown photo "${n}". Choose from: ${Object.keys(JOBS).join(", ")}`);
    process.exit(2);
  }
}

const key = loadDotEnvLocal().META_API_KEY;
if (!key) {
  console.error("META_API_KEY is missing. Nothing was called.");
  process.exit(2);
}

mkdirSync("public/demo/venues", { recursive: true });
for (const name of names) {
  const job = JOBS[name];
  const startedAt = new Date().toISOString();
  const res = await fetch("https://api.meta.ai/v1/images/generations", {
    method: "POST",
    headers: { "content-type": "application/json", authorization: `Bearer ${key}` },
    body: JSON.stringify({ model: MODEL, prompt: job.prompt, size: name.startsWith("venue-") ? "1536x1024" : "1024x1024", n: 1 }),
  });
  if (!res.ok) {
    console.error(`${name}: image request failed: provider-http-${res.status}`);
    process.exit(1);
  }
  const data = await res.json();
  const first = data?.data?.[0];
  let bytes;
  if (typeof first?.b64_json === "string") {
    bytes = Buffer.from(first.b64_json, "base64");
  } else if (typeof first?.url === "string") {
    const dl = await fetch(first.url);
    if (!dl.ok) {
      console.error(`${name}: image download failed: provider-http-${dl.status}`);
      process.exit(1);
    }
    bytes = Buffer.from(await dl.arrayBuffer());
  } else {
    console.error(`${name}: unexpected image payload keys: ${Object.keys(data).join(",")}`);
    process.exit(1);
  }
  writeFileSync(job.file, bytes);
  // llm_calls record: only metadata + cost/usage as returned by the provider.
  const record = { at: startedAt, model: MODEL, purpose: `home-photo:${name}`, bytes: bytes.length, usage: data.usage ?? null, cost_usd: typeof data.cost_usd === "number" ? data.cost_usd : null };
  console.log(`llm_calls ${JSON.stringify(record)}`);
  console.log(`saved ${job.file} (${bytes.length} bytes)`);
}
